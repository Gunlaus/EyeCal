"""Generate the EyeCal 16 × 16 blue-noise rank texture. Requires NumPy."""
from pathlib import Path
from random import Random

import numpy as np

SIDE = 16
COUNT = SIDE * SIDE
SEED = 29717
SIGMA = 1.5

indices = np.arange(COUNT)
x, y = indices % SIDE, indices // SIDE
dx = abs(x[:, None] - x)
dy = abs(y[:, None] - y)
dx, dy = np.minimum(dx, SIDE - dx), np.minimum(dy, SIDE - dy)
kernel = np.exp(-(dx * dx + dy * dy) / (2 * SIGMA * SIGMA))


def tightest_cluster(mask, density):
    return np.argmax(np.where(mask, density, -np.inf))


def largest_void(mask, density):
    return np.argmin(np.where(mask, np.inf, density))


initial = np.zeros(COUNT, dtype=bool)
initial[Random(SEED).sample(range(COUNT), COUNT // 8)] = True
density = kernel[initial].sum(axis=0)
for _ in range(10000):
    cluster = tightest_cluster(initial, density)
    initial[cluster] = False
    density -= kernel[cluster]
    void = largest_void(initial, density)
    initial[void] = True
    density += kernel[void]
    if cluster == void:
        break
else:
    raise RuntimeError("Void-and-cluster seed did not converge")

ranks = np.empty(COUNT, dtype=int)
mask, field = initial.copy(), density.copy()
for rank in reversed(range(COUNT // 8)):
    cluster = tightest_cluster(mask, field)
    ranks[cluster] = rank
    mask[cluster] = False
    field -= kernel[cluster]

mask, field = initial.copy(), density.copy()
for rank in range(COUNT // 8, COUNT):
    void = largest_void(mask, field)
    ranks[void] = rank
    mask[void] = True
    field += kernel[void]

words = [sum(int(rank) << (8 * i) for i, rank in enumerate(row))
         for row in ranks.reshape(-1, 4)]
lines = ["// Generated by generate.py. CC0-1.0. Four red-channel texels per word."]
for start in range(0, len(words), 4):
    lines.append(", ".join(f"0x{word:08x}u" for word in words[start:start + 4]) +
                 ("," if start + 4 < len(words) else ""))
Path(__file__).with_name("blue_noise_ranks.inc").write_text("\n".join(lines) + "\n")
